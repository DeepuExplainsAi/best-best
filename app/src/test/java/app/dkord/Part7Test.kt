package app.dkord

import app.dkord.data.stream.NoVideoException
import app.dkord.data.stream.StreamError
import app.dkord.data.stream.SubtitleCandidate
import app.dkord.data.stream.SubtitlePicker
import app.dkord.data.stream.VideoCandidate
import app.dkord.data.stream.VideoPicker
import app.dkord.ui.player.VideoErrors
import app.dkord.ui.player.VideoFailure
import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class Part7Test {
    private fun v(h: Int, mime: String = "video/mp4", url: String = "https://x/$h") = VideoCandidate(url, mime, h)
    private fun s(lang: String, auto: Boolean = false, mime: String = "text/vtt", url: String = "https://s/$lang$auto") =
        SubtitleCandidate(url, mime, lang, lang.uppercase(), auto)

    @Test fun picksBestUnderCap() = assertEquals(720, VideoPicker.pick(listOf(v(360), v(720), v(1080)))!!.height)
    @Test fun fallsBackToLowestAboveCap() = assertEquals(1080, VideoPicker.pick(listOf(v(2160), v(1080)))!!.height)
    @Test fun rejectsNonHttpsAndNonVideo() = assertNull(VideoPicker.pick(listOf(v(360, url = "http://x"), v(360, mime = "audio/mp4"))))
    @Test fun noStreamsIsNull() = assertNull(VideoPicker.pick(emptyList()))

    @Test fun subtitlesFilterUnsupportedAndPreferManual() {
        val out = SubtitlePicker.pick(listOf(s("en", auto = true), s("en"), s("fr", mime = "application/json"), s("de")))
        assertEquals(listOf("de" to false, "en" to false, "en" to true), out.map { it.language to it.autoGenerated })
    }
    @Test fun noSubtitlesIsEmpty() = assertEquals(emptyList<SubtitleCandidate>(), SubtitlePicker.pick(emptyList()))

    @Test fun errorMapping() {
        assertEquals(VideoFailure.NO_VIDEO, VideoErrors.of(NoVideoException("x")).reason)
        assertEquals(VideoFailure.RESTRICTED, VideoErrors.of(StreamError.AgeRestricted()).reason)
        assertEquals(VideoFailure.NETWORK, VideoErrors.of(StreamError.Network(RuntimeException("x"))).reason)
    }
}
