package app.dkord.data.stream

/** Muxed (video + audio in one file) progressive stream. Separate from audio streams on purpose. */
data class VideoCandidate(val url: String, val mimeType: String, val height: Int)

data class SubtitleCandidate(val url: String, val mimeType: String, val language: String, val label: String, val autoGenerated: Boolean)

data class ResolvedVideo(
    val videoId: String,
    val video: VideoCandidate,
    val subtitles: List<SubtitleCandidate>,
    val expiresAtMs: Long,
)

/** User-facing reasons video cannot start. Audio playback is unaffected by any of them. */
class NoVideoException(message: String) : java.io.IOException(message)

object VideoPicker {
    const val MAX_HEIGHT = 720

    /** Best muxed mp4/webm at or below [maxHeight]; the lowest above it if nothing fits. Null if no usable stream. */
    fun pick(all: List<VideoCandidate>, maxHeight: Int = MAX_HEIGHT): VideoCandidate? {
        val usable = all.filter { it.url.startsWith("https://") && it.mimeType.startsWith("video/") }
        return usable.filter { it.height <= maxHeight }.maxByOrNull { it.height } ?: usable.minByOrNull { it.height }
    }
}

object SubtitlePicker {
    private val supported = setOf("text/vtt", "application/ttml+xml", "application/x-subrip")

    /** Only formats Media3 can render, one per language (manual captions win over auto-generated), sorted by label. */
    fun pick(all: List<SubtitleCandidate>): List<SubtitleCandidate> =
        all.filter { it.mimeType in supported && it.url.startsWith("https://") }
            .sortedBy { it.autoGenerated }
            .distinctBy { it.language to it.autoGenerated }
            .sortedWith(compareBy({ it.autoGenerated }, { it.label }))
}
